"""Emit the README results table straight from the report JSONs.

    python -m spine.eval.compare --split test > docs/_table_test.md

No hand-typed numbers anywhere in the documentation. If a number appears in the
README, this script produced it from an artifact, which means a reviewer can
regenerate it and catch you if it drifted.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROWS = [
    ("json_valid_strict", "JSON validity (no repair)", "pct"),
    ("needed_repair", "Needed output repair", "pct_lower"),
    ("schema_valid", "Schema valid", "pct"),
    ("exact_match", "**Exact match (full record)**", "pct"),
    ("macro_field_accuracy", "Macro field accuracy", "pct"),
    ("interface_f1", "Interface F1", "pct"),
    ("refusal_f1", "Refusal F1", "pct"),
    ("missed_abstain_rate", "Missed abstain (invented incident)", "pct_lower"),
    ("over_abstain_rate", "Over-abstain (dropped incident)", "pct_lower"),
    ("grounding_rate", "Evidence span grounded", "pct"),
    ("examples_per_second", "Throughput (ex/s)", "raw"),
]


def fmt(value, kind: str) -> str:
    if value is None:
        return "-"
    if kind == "raw":
        return f"{value:.2f}"
    return f"{value * 100:.1f}%"


def delta(new, old, kind: str) -> str:
    if new is None or old is None:
        return "-"
    d = (new - old) * (1 if kind != "raw" else 1)
    sign = "+" if d >= 0 else ""
    if kind == "raw":
        return f"{sign}{d:.2f}"
    good = d < 0 if kind == "pct_lower" else d > 0
    arrow = "▲" if good else ("▼" if abs(d) > 1e-9 else "–")
    return f"{arrow} {sign}{d * 100:.1f} pts"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--reports", type=Path, default=Path("reports"))
    ap.add_argument("--split", default="test")
    ap.add_argument("--tags", nargs="*", default=["base_prompted", "sft", "dpo"])
    ap.add_argument("--names", nargs="*", default=["Base + best prompt", "Phase 1: SFT", "Phase 2: SFT+DPO"])
    ap.add_argument("--delta-against", default=None, help="defaults to the first tag")
    args = ap.parse_args()

    reps: dict[str, dict] = {}
    for tag in args.tags:
        p = args.reports / f"{tag}_{args.split}.json"
        if p.exists():
            reps[tag] = json.loads(p.read_text())
    if not reps:
        raise SystemExit(f"no reports found in {args.reports} for split={args.split}")

    args.delta_against = args.delta_against or args.tags[0]
    names = {t: n for t, n in zip(args.tags, args.names)}
    present = [t for t in args.tags if t in reps]
    header = "| Metric | " + " | ".join(names.get(t, t) for t in present) + " | Δ vs baseline |"
    sep = "|---" * (len(present) + 2) + "|"
    lines = [header, sep]
    ref = reps.get(args.delta_against)
    last = reps[present[-1]]
    for key, label, kind in ROWS:
        cells = [fmt(reps[t].get(key), kind) for t in present]
        d = delta(last.get(key), ref.get(key), kind) if ref is not None and ref is not last else "-"
        lines.append(f"| {label} | " + " | ".join(cells) + f" | {d} |")

    n = last.get("n")
    print(f"<!-- generated by `python -m spine.eval.compare --split {args.split}` -->")
    print(f"**Split:** `{args.split}` ({n} examples)\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
